import argparse
import json
import os
import os.path as osp
from collections import defaultdict

import cv2
import mmengine
import numpy as np


AI_DOT_CLASSES = (
    'airplane', 'bridge', 'storage-tank', 'ship', 'swimming-pool',
    'vehicle', 'person', 'wind-mill')

DIOR_CLASSES = (
    'airplane', 'airport', 'baseballfield', 'basketballcourt', 'bridge',
    'chimney', 'dam', 'Expressway-Service-area',
    'Expressway-toll-station', 'golffield', 'groundtrackfield', 'harbor',
    'overpass', 'ship', 'stadium', 'storagetank', 'tenniscourt',
    'trainstation', 'vehicle', 'windmill')

DATASET_CLASSES = {
    'ai_dot': AI_DOT_CLASSES,
    'dior': DIOR_CLASSES,
}


def parse_args():
    parser = argparse.ArgumentParser(
        description='Draw selected prediction and annotation boxes.')
    parser.add_argument('result_pkl', help='results.pkl generated by test.py')
    parser.add_argument('ann_file', help='COCO-format annotation json')
    parser.add_argument('img_root', help='image root directory')
    parser.add_argument(
        '--out-dir', default='results/vis_ship_vehicle', help='output dir')
    parser.add_argument(
        '--score-thr', type=float, default=0.3, help='prediction score thr')
    parser.add_argument(
        '--target-classes',
        nargs='+',
        default=['ship', 'vehicle'],
        help='classes to draw')
    parser.add_argument(
        '--dataset',
        choices=sorted(DATASET_CLASSES),
        default='dior',
        help='dataset class preset used to decode prediction labels')
    parser.add_argument(
        '--classes',
        nargs='+',
        default=None,
        help='dataset classes in training label order. If set, overrides '
        '--dataset')
    parser.add_argument(
        '--show-gt-label',
        action='store_true',
        help='draw labels for ground-truth boxes')
    return parser.parse_args()


def to_numpy(value):
    if value is None:
        return None
    if hasattr(value, 'detach'):
        value = value.detach().cpu().numpy()
    elif hasattr(value, 'cpu') and hasattr(value, 'numpy'):
        value = value.cpu().numpy()
    else:
        value = np.asarray(value)
    return value


def get_field(obj, name, default=None):
    if obj is None:
        return default
    if isinstance(obj, dict):
        return obj.get(name, default)
    return getattr(obj, name, default)


def get_metainfo(result):
    metainfo = get_field(result, 'metainfo', None)
    if metainfo is None:
        metainfo = get_field(result, 'img_meta', None)
    if metainfo is None:
        metainfo = {}
    return metainfo


def get_pred_instances(result):
    pred = get_field(result, 'pred_instances', None)
    if pred is None and isinstance(result, dict):
        pred = result
    return pred


def get_img_id(result):
    metainfo = get_metainfo(result)
    for key in ('img_id', 'image_id', 'id'):
        if key in metainfo:
            return metainfo[key]
        value = get_field(result, key, None)
        if value is not None:
            return value
    return None


def load_coco_ann(ann_file):
    with open(ann_file, 'r', encoding='utf-8') as f:
        coco = json.load(f)

    images = coco.get('images', [])
    categories = coco.get('categories', [])
    annotations = coco.get('annotations', [])

    img_id_to_info = {img['id']: img for img in images}
    cat_id_to_name = {cat['id']: cat['name'] for cat in categories}
    anns_by_img = defaultdict(list)
    for ann in annotations:
        anns_by_img[ann['image_id']].append(ann)
    return images, img_id_to_info, cat_id_to_name, anns_by_img


def normalize_label(label):
    if isinstance(label, bytes):
        return label.decode('utf-8')
    return str(label)


def draw_text_with_bg(img, text, org, color, font_scale=0.5, thickness=1):
    font = cv2.FONT_HERSHEY_SIMPLEX
    x, y = int(org[0]), int(org[1])
    (tw, th), baseline = cv2.getTextSize(text, font, font_scale, thickness)
    y1 = max(y - th - baseline, 0)
    y2 = max(y, th + baseline)
    cv2.rectangle(img, (x, y1), (x + tw, y2), color, -1)
    cv2.putText(
        img, text, (x, y2 - baseline), font, font_scale, (255, 255, 255),
        thickness, cv2.LINE_AA)


def draw_box(img, bbox, color, label=None, score=None, thickness=2):
    x1, y1, x2, y2 = [int(round(v)) for v in bbox]
    h, w = img.shape[:2]
    x1 = max(0, min(x1, w - 1))
    x2 = max(0, min(x2, w - 1))
    y1 = max(0, min(y1, h - 1))
    y2 = max(0, min(y2, h - 1))
    if x2 <= x1 or y2 <= y1:
        return
    cv2.rectangle(img, (x1, y1), (x2, y2), color, thickness)

    if label is not None:
        if score is None:
            text = label
        else:
            # Match MMDetection's common label + confidence display style.
            text = f'{label} {score:.2f}'
        draw_text_with_bg(img, text, (x1, y1), color)


def xywh_to_xyxy(bbox):
    x, y, w, h = bbox
    return [x, y, x + w, y + h]


def collect_result_by_img_id(results):
    result_by_img_id = {}
    for idx, result in enumerate(results):
        img_id = get_img_id(result)
        if img_id is not None:
            result_by_img_id[img_id] = result
        result_by_img_id.setdefault(idx, result)
    return result_by_img_id


def draw_one_image(img, result, gt_anns, cat_id_to_name, classes,
                   target_names, score_thr, show_gt_label):
    pred_color = (0, 0, 255)  # red in BGR
    gt_color = (0, 255, 0)  # green in BGR
    target_names = set(target_names)

    pred = get_pred_instances(result)
    bboxes = to_numpy(get_field(pred, 'bboxes', []))
    labels = to_numpy(get_field(pred, 'labels', []))
    scores = to_numpy(get_field(pred, 'scores', []))

    if bboxes is not None and labels is not None and scores is not None:
        for bbox, label, score in zip(bboxes, labels, scores):
            label = int(label)
            score = float(score)
            if label < 0 or label >= len(classes) or score < score_thr:
                continue
            class_name = normalize_label(classes[label])
            if class_name not in target_names:
                continue
            draw_box(img, bbox, pred_color, class_name, score)

    for ann in gt_anns:
        class_name = cat_id_to_name.get(ann['category_id'], '')
        if class_name not in target_names:
            continue
        label = class_name if show_gt_label else None
        draw_box(img, xywh_to_xyxy(ann['bbox']), gt_color, label=label)

    return img


def main():
    args = parse_args()
    classes = args.classes
    if classes is None:
        classes = list(DATASET_CLASSES[args.dataset])
    results = mmengine.load(args.result_pkl)
    images, _, cat_id_to_name, anns_by_img = load_coco_ann(args.ann_file)
    result_by_img_id = collect_result_by_img_id(results)
    mmengine.mkdir_or_exist(args.out_dir)

    drawn = 0
    for index, img_info in enumerate(images):
        img_id = img_info['id']
        result = result_by_img_id.get(img_id, result_by_img_id.get(index))
        if result is None:
            continue

        file_name = img_info['file_name']
        img_path = osp.join(args.img_root, file_name)
        img = cv2.imread(img_path)
        if img is None:
            print(f'[WARN] Cannot read image: {img_path}')
            continue

        img = draw_one_image(
            img=img,
            result=result,
            gt_anns=anns_by_img.get(img_id, []),
            cat_id_to_name=cat_id_to_name,
            classes=classes,
            target_names=args.target_classes,
            score_thr=args.score_thr,
            show_gt_label=args.show_gt_label)

        out_path = osp.join(args.out_dir, osp.basename(file_name))
        mmengine.mkdir_or_exist(osp.dirname(out_path))
        cv2.imwrite(out_path, img)
        drawn += 1

    print(f'Done. Saved {drawn} images to {args.out_dir}')


if __name__ == '__main__':
    main()
